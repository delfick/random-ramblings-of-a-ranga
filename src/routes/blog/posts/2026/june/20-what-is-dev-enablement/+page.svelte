<p>
  I wrote this in work slack in June 2025 and I think it's worth repeating on my blog, and
  so that's what this post is!
</p>

<p>
  My role at work is within our "developer experience" team (which we call "developer
  foundations") and I feel the idea of "devEx" is a bit of a suitcase concept (what it
  means is determined by the person reading the word much more than any kind of real
  common concrete definition). I feel it's a similar problem that "devops" as a concept
  has in our industry (something I did for around 8 years before I managed to find my way
  back to application development).
</p>

<p>
  The way I see it is we are enablement for application developers, which means we have
  custodianship over:
</p>

<ul>
  <li>
    Ensuring application developers work in an environment where they are productive and
    have the ability to grow as developers
  </li>
  <li>
    Ensuring that the default and accessible approach to application developers results in
    code that ages well (velocity comes from rarely revisiting code that is already
    considered "done")
  </li>
</ul>

<p>
  With an approach that is human centric rather than technology centric, as
  <strong>
    the goal is to grow engineers far more than it is about hiding challenges from
    developers.
  </strong>
</p>

<p>And we have at our disposal</p>

<ul>
  <li>
    Supporting developer's curiosity and passion for making infrastructure better
    (frameworks, tests, tooling, etc)
  </li>
  <li>Advocating for better processes</li>
  <li>Advocating for better design practices</li>
  <li>Setting the general technical direction</li>
  <li>
    Assisting with feature-adjacent code migrations (i.e. we want developers to fix things
    as they go, but sometimes you do just need people who are dedicated to cleaning up
    things like linter violations)
  </li>
  <li>
    Working on the tooling (I feel people often mistake this point as the entirety of
    devEx as opposed to only one part of it)
  </li>
</ul>

<p>
  It's not our place to decide what the code does, it's our place to steer how the code
  works and
  <strong>
    ensure that changes in the moment don't result in preventable headaches in the future,
  </strong>
  and also to ensure that foreseeable headaches in the future get resources and attention well
  before they become very difficult to resolve.
</p>

<p>
  We also have a boundary with other enablement teams like platform and general IT
  support. Where we can be a bridge that guides developers on how to use the work those
  teams provide and let those teams decide the technical details of how those things work.
</p>

<p>
  In a sentence, the way I see it is
  <strong>
    anything development based that distracts a developer from getting a feature across
    the line
  </strong>
  (tech debt, tooling/CI inefficiency, tooling deficiency, dependency management, framework
  design, code re-use, linter configuration, human processes, documentation, general developer
  practices)
  <strong> are foundational and part of our focus. </strong>
</p>

<p>
  We aren't here to hide those challenges from the developers, but we are here to provide
  developers with the support they need to focus on the tasks they are given.
</p>
